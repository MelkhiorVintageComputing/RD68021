#!/usr/bin/env python3
"""Generate rtl/gen/ from the tables in this directory, and refuse to if they
are wrong.

    python3 tools/ucode/assemble.py            # regenerate
    python3 tools/ucode/assemble.py --check    # fail if what is checked in is stale

The generated files are committed, so a build needs no Python. `make ucode-check`
is the first thing `make check` runs, so they cannot drift from their source.

The generator is also the design-rule checker. Some properties cannot be stated in
RTL -- that no two checkpointed registers share a bit of the fault frame, that the
short frame carries no private state, that every frame is exactly as long as the
manual says -- so they are stated here and fail the build instead.

As of M4 this emits the frame package. The microword, the decoders and the
microcode store arrive in M5.
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
GEN = os.path.join(ROOT, 'rtl', 'gen')
sys.path.insert(0, HERE)

import frames                                                   # noqa: E402
import isa                                                      # noqa: E402
import program                                                  # noqa: E402

BANNER = """// RD68021 - SystemVerilog MC68020
//
// GENERATED by tools/ucode/assemble.py from tools/ucode/frames.py. Do not edit:
// `make ucode-check` compares this file against its source and fails the build if
// they have drifted.
//
"""


def frame_pkg():
    out = [BANNER]
    out.append("""// The six exception stack frames -- UM Table 6-5 -- and the offsets this design
// keeps its own state at inside the long one.
//
// One wrong offset here is a silent demand-paging failure: the frame would be
// written correctly enough to pass its own format check and read back one word
// out. tools/ucode/frames.py is the single place any of these numbers exists.

`ifndef RD68021_FRAME_PKG_SV
`define RD68021_FRAME_PKG_SV

package rd68021_frame_pkg;

  // ==========================================================================
  // Frame sizes, in bytes, as the stack pointer must be adjusted by
  // ==========================================================================""")
    for fmt in sorted(frames.FRAMES):
        f = frames.FRAMES[fmt]
        out.append('  localparam int FRAME_%X_BYTES = %d;   // %s, %d words'
                   % (fmt, 2 * f['words'], f['name'], f['words']))

    out.append("""
  // ==========================================================================
  // Architecturally named fields -- UM Table 6-5
  //
  // OFF is the byte offset from the stack pointer; a field present in more than
  // one frame is at the same offset in each, which is what makes one set of
  // constants right for all of them.
  // ==========================================================================""")
    seen = {}
    for fmt in sorted(frames.FRAMES):
        for off, n, field in frames.FRAMES[fmt]['slots']:
            if field in ('internal', 'version'):
                continue
            if field in seen:
                if seen[field] != (off, n):
                    raise SystemExit('assemble: field %r is at +$%02X in one frame '
                                     'and +$%02X in another -- the generator assumes '
                                     'it is not' % (field, seen[field][0], off))
                continue
            seen[field] = (off, n)
            out.append('  localparam int OFF_%-13s = \'h%02X;   // %d word%s, %s'
                       % (field.upper(), off, n, '' if n == 1 else 's',
                          frames.ARCH_FIELDS[field]))

    out.append("""
  // ==========================================================================
  // The version number -- UM 6.1.12
  //
  // "The version number is located in the most significant nibble (bits 15-12)
  // of the word at location SP + $36 in the long stack frame." RTE compares it
  // with its own and takes a format error if they differ, which is the contract
  // that makes this design's private encoding of the internal words legitimate.
  // It is also why the SHORT frame, which has no version field, carries none of
  // them. See doc/manual-contradictions.md for why the offset is $36.
  // ==========================================================================""")
    out.append('  localparam int         OFF_VERSION  = \'h%02X;' % frames.VERSION_OFFSET)
    out.append('  localparam int         VERSION_HI   = %d;' % frames.VERSION_HI)
    out.append('  localparam int         VERSION_LO   = %d;' % frames.VERSION_LO)
    out.append('  localparam logic [3:0] FRAME_VERSION = 4\'h%X;' % frames.VERSION)

    have, use, spare = frames.budget()
    out.append("""
  // ==========================================================================
  // This design's own state, in the long frame's internal words
  //
  // %d bits available, %d used, %d words spare. Recompute this whenever
  // something is added: doc/checkpoint.md carries the same table, printed from
  // the same source.
  // ==========================================================================""" % (have, use, len(spare)))
    for off, hi, lo, name, bits, what in frames.INTERNAL:
        out.append('  localparam int OFF_%-11s = \'h%02X;   // %2d bits, %s'
                   % ('I_' + name.upper(), off, bits, what))
        out.append('  localparam int %-15s = %d;'
                   % ('I_' + name.upper() + '_HI', hi))
        out.append('  localparam int %-15s = %d;'
                   % ('I_' + name.upper() + '_LO', lo))

    out.append("""
endpackage

`endif""")
    return '\n'.join(out) + '\n'


def doc_tables():
    """The tables doc/checkpoint.md carries, printed from the same source."""
    out = []
    out.append('### The frames\n')
    out.append('| Format | Words | Name | Layout |')
    out.append('|---|--:|---|---|')
    for fmt in sorted(frames.FRAMES):
        f = frames.FRAMES[fmt]
        bits = []
        for off, n, field in f['slots']:
            label = field if field != 'internal' else 'internal'
            bits.append('`+$%02X` %s%s' % (off, label,
                                           '' if n == 1 else ' ×%d' % n))
        out.append('| `$%X` | %d | %s | %s |'
                   % (fmt, f['words'], f['name'], ', '.join(bits)))

    out.append('\n### The private words of the long frame\n')
    out.append('| Offset | Bits | Register | What |')
    out.append('|---|---|---|---|')
    for off, hi, lo, name, bits, what in frames.INTERNAL:
        r = '%d' % hi if hi == lo else '%d:%d' % (hi, lo)
        out.append('| `+$%02X` | %s | `%s` | %s |' % (off, r, name, what))
    have, use, spare = frames.budget()
    out.append('\n**%d bits available, %d used, %d words spare** (%s).'
               % (have, use, len(spare),
                  ', '.join('`+$%02X`' % w for w in spare)))

    out.append('\n### The frozen set\n')
    out.append('| Unit | Register | Bits | Lands in | |')
    out.append('|---|---|--:|---|---|')
    for unit, reg, bits, slot, note in frames.CHECKPOINT:
        out.append('| `%s` | `%s` | %d | `%s` | %s |' % (unit, reg, bits, slot, note))

    out.append('\n### Not checkpointed, and why\n')
    out.append('| | |')
    out.append('|---|---|')
    for what, why in frames.NOT_CHECKPOINTED:
        out.append('| %s | %s |' % (what, why))
    return '\n'.join(out) + '\n'


# --------------------------------------------------------------------------
# The microcode store
# --------------------------------------------------------------------------
def assemble_words():
    """Every microword as an integer, with `next` resolved.

    Fall-through is the default: a microword whose `seq` is NEXT and which names
    no successor runs the one after it. An unset field can therefore never mean
    micro-address zero by accident.
    """
    lay, width = isa.layout()
    out = []
    for i, (fields, _comment) in enumerate(program.WORDS):
        word = 0
        for name, (lsb, w) in lay.items():
            enc = isa.FIELDS[name][1]
            default = isa.FIELDS[name][2]
            v = fields.get(name, default)
            if name == 'next':
                if name in fields:
                    v = program.entry(fields['next']) if isinstance(v, str) else v
                else:
                    v = i + 1        # fall through
            elif enc is not None:
                if v not in enc:
                    raise SystemExit('assemble: microword %d: %r is not a value of '
                                     'field %r' % (i, v, name))
                v = enc[v]
            if v < 0 or v >= (1 << w):
                raise SystemExit('assemble: microword %d: field %r value %d does '
                                 'not fit in %d bits' % (i, name, v, w))
            word |= v << lsb
        out.append(word)
    return out, width


# --------------------------------------------------------------------------
# The opcode decoder
#
# Written as an ordered list -- first match wins -- and emitted as DISJOINT
# patterns, because Quartus builds an ordered casez as a priority chain and does
# not flatten it. On the MC68010 project that cost 1401 patterns 498 logic levels
# and 4.67 MHz where Vivado and yosys flattened the same source.
#
# The order is resolved once, here, and the two tables are then proved to agree
# over all 65536 opcodes.
# --------------------------------------------------------------------------
def cube_minus(a, b):
    """The cubes covering a but not b."""
    n = len(a)
    for i in range(n):
        if a[i] != '-' and b[i] != '-' and a[i] != b[i]:
            return [a]                      # disjoint already
    out = []
    cur = list(a)
    for i in range(n):
        if b[i] != '-' and a[i] == '-':
            piece = list(cur)
            piece[i] = '1' if b[i] == '0' else '0'
            out.append(''.join(piece))
            cur[i] = b[i]
    return out


def make_disjoint(pats):
    out = []
    for i, (p, t, m) in enumerate(pats):
        cubes = [p]
        for q, _, _ in pats[:i]:
            nxt = []
            for c in cubes:
                nxt.extend(cube_minus(c, q))
            cubes = nxt
        if not cubes:
            raise SystemExit('assemble: opcode pattern %s (%s) is completely '
                             'shadowed by an earlier one' % (p, m))
        for c in cubes:
            out.append((c, t, m))
    return out


def _match(pattern, op):
    n = len(pattern)
    for i, c in enumerate(pattern):
        if c == '-':
            continue
        if ((op >> (n - 1 - i)) & 1) != int(c):
            return False
    return True


def check_disjoint(ordered, disjoint, width=16):
    """The two tables agree over every input, and no two disjoint cubes overlap."""
    bad = []
    for op in range(1 << width):
        a = None
        for p, t, _ in ordered:
            if _match(p, op):
                a = t
                break
        hits = [t for p, t, _ in disjoint if _match(p, op)]
        if len(hits) > 1:
            bad.append('input $%05X matches %d disjoint patterns' % (op, len(hits)))
            if len(bad) > 4:
                break
        b = hits[0] if hits else None
        if a != b:
            bad.append('input $%05X: ordered says %r, disjoint says %r'
                       % (op, a, b))
            if len(bad) > 4:
                break
    return bad


def ucode_pkg():
    lay, width = isa.layout()
    out = [BANNER]
    out.append("""// The microword: every field position and every encoding the microcode can use,
// so that the RTL and the microcode cannot drift apart. tools/ucode/isa.py is the
// only place any of this is decided.

`ifndef RD68021_UCODE_PKG_SV
`define RD68021_UCODE_PKG_SV

package rd68021_ucode_pkg;
""")
    out.append('  localparam int UW    = %d;   // microword width' % width)
    out.append('  localparam int UADDR = %d;   // micro-address width' % isa.UADDR_BITS)
    out.append('')
    for name, (lsb, w) in lay.items():
        out.append('  localparam int U_%s_LSB = %d;' % (name.upper(), lsb))
        out.append('  localparam int U_%s_W   = %d;' % (name.upper(), w))
    out.append('')
    for name, (w, e, _d) in isa.FIELDS.items():
        if e is None:
            continue
        for k, v in e.items():
            out.append("  localparam logic [%d:0] U_%s_%s = %d'd%d;"
                       % (w - 1, name.upper(), k, w, v))
        out.append('')
    out.append('  // Named entry points.')
    for lbl in ('reset', 'illegal'):
        out.append('  localparam logic [UADDR-1:0] ENTRY_%s = %d\'d%d;'
                   % (lbl.upper(), isa.UADDR_BITS, program.entry(lbl)))
    out.append("""
endpackage

`endif""")
    return '\n'.join(out) + '\n'


def ucode_rom():
    words, width = assemble_words()
    out = [BANNER]
    out.append("""// The microcode store.
//
// Read at `addr`, which the sequencer drives with the NEXT micro-address rather
// than the current one, and registered: the same word arrives at the same time as
// the micro-address it belongs to, with no clock lost and with a memory instead of
// logic. The reset value is the word at the reset entry point, which is what makes
// this a reset register like any other rather than an exemption from the rule.

// The port widths are literals rather than rd68021_ucode_pkg::UADDR-1 and UW-1:
// iverilog rejects a package-scoped constant in a port declaration with a bare
// "syntax error" and no hint as to which token it minded. The generator knows
// both numbers, so it writes them out. doc/coding-standard.md.
module rd68021_ucode_rom (
    input  logic          clk,
    input  logic          rst_n,
    input  logic [%d:0]   addr,
    output logic [%d:0]   uw
);

  // Say which memory and stop it being a choice: Vivado's ROM inference in its
  // own synthesis report is preliminary and timing optimisation may reverse it
  // with no message, and Quartus honours ramstyle where Vivado honours rom_style.
  (* rom_style = "block", ramstyle = "M9K" *)
  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      uw <= %d'h%0*X;
    end else begin
      unique case (addr)""" % (isa.UADDR_BITS - 1, width - 1,
                               width, (width + 3) // 4,
                               words[program.entry('reset')]))
    for i, w in enumerate(words):
        _f, comment = program.WORDS[i]
        out.append("        %d'd%-5d: uw <= %d'h%0*X;%s"
                   % (isa.UADDR_BITS, i, width, (width + 3) // 4, w,
                      ('   // ' + comment) if comment else ''))
    out.append("""        default:      uw <= %d'h%0*X;   // the illegal entry
      endcase
    end
  end

endmodule""" % (width, (width + 3) // 4, words[program.entry('illegal')]))
    return '\n'.join(out) + '\n'


def decode_rom():
    ordered = program.PATTERNS
    disjoint = make_disjoint(ordered)
    bad = check_disjoint(ordered, disjoint)
    if bad:
        raise SystemExit('assemble: the disjoint decode table does not agree with '
                         'the ordered one:\n  ' + '\n  '.join(bad))
    out = [BANNER]
    out.append("""// The opcode decoder: an instruction word in, a micro-address out.
//
// The patterns in tools/ucode/program.py are ORDERED -- first match wins -- and
// are emitted here as DISJOINT ones, because Quartus builds an ordered casez as a
// priority chain and does not flatten it. assemble.py resolves the order once, in
// Python, and proves the two tables agree over all 65536 opcodes.
//
// %d ordered patterns became %d disjoint ones.

module rd68021_decode_rom (
    input  logic [15:0]                         ir,
    output logic [%d:0] entry,
    output logic                                illegal
);

  always_comb begin
    illegal = 1'b0;
    casez (ir)""" % (len(ordered), len(disjoint), isa.UADDR_BITS - 1))
    for p, t, m in disjoint:
        out.append("      16'b%s: entry = %d'd%d;   // %s"
                   % (p.replace('-', '?'), isa.UADDR_BITS, program.entry(t), m))
    out.append("""      default: begin
        entry   = rd68021_ucode_pkg::ENTRY_ILLEGAL;
        illegal = 1'b1;
      end
    endcase
  end

endmodule""")
    return '\n'.join(out) + '\n'


def eadec_rom():
    ordered = program.EAPATTERNS
    disjoint = make_disjoint(ordered)
    bad = check_disjoint(ordered, disjoint, width=17)
    if bad:
        raise SystemExit('assemble: the disjoint extension-word table does not '
                         'agree with the ordered one:\n  ' + '\n  '.join(bad))
    out = [BANNER]
    out.append("""// The extension-word decoder: the shape of an effective address in, a
// micro-address out.
//
// A full extension word decides how many words of base and outer displacement
// follow and whether a memory indirection happens -- five bus-steering decisions
// taken from a word that has only just been read. Branching on them microword by
// microword would put all five into the bus request's fan-in, which is the one
// thing the microcode may not do. Resolving them once, in hardware, into a
// micro-address puts none of them there. It is the opcode decoder's trick on a
// different word.
//
// The seventeenth bit is not part of the extension word. It says whether the
// base of the address is the program counter or an address register, which is in
// the OPCODE -- so the microword supplies it.
//
// %d ordered patterns became %d disjoint ones.

module rd68021_eadec_rom (
    input  logic        pc_base,
    input  logic [15:0] xw,
    output logic [UA:0] entry,
    output logic        reserved
);

  always_comb begin
    reserved = 1'b0;
    casez ({pc_base, xw})
""" % (len(ordered), len(disjoint)))
    out[-1] = out[-1].replace('[UA:0]', '[%d:0]' % (isa.UADDR_BITS - 1))
    for p, t, m in disjoint:
        out.append("      17'b%s: entry = %d'd%d;   // %s"
                   % (p.replace('-', '?'), isa.UADDR_BITS, program.entry(t), m))
    out.append("""      default: begin
        entry    = rd68021_ucode_pkg::ENTRY_ILLEGAL;
        reserved = 1'b1;
      end
    endcase
  end

endmodule""")
    return '\n'.join(out) + '\n'


def eamode_rom():
    """The addressing-mode decoder: six bits of stage D in, a micro-address out.

    The same trick as the opcode and extension-word decoders, one level down.
    Without it every instruction with an effective address needs one opcode
    pattern per addressing mode -- eighteen of them, times eighty instructions --
    and the decode table stops being something anyone can read.
    """
    ordered = program.MODEPATTERNS
    disjoint = make_disjoint(ordered)
    bad = check_disjoint(ordered, disjoint, width=6)
    if bad:
        raise SystemExit('assemble: the disjoint addressing-mode table does not '
                         'agree with the ordered one:\n  ' + '\n  '.join(bad))
    out = [BANNER]
    out.append("""// The addressing-mode decoder: the mode and register fields of the instruction
// word in, the micro-address of the routine that computes that address out.
//
// %d ordered patterns became %d disjoint ones.

module rd68021_eamode_rom (
    input  logic  [5:0] mr,
    output logic [%d:0] entry,
    output logic        illegal
);

  always_comb begin
    illegal = 1'b0;
    casez (mr)
""" % (len(ordered), len(disjoint), isa.UADDR_BITS - 1))
    for p, t, m in disjoint:
        out.append("      6'b%s: entry = %d'd%d;   // %s"
                   % (p.replace('-', '?'), isa.UADDR_BITS, program.entry(t), m))
    out.append("""      default: begin
        entry   = rd68021_ucode_pkg::ENTRY_ILLEGAL;
        illegal = 1'b1;
      end
    endcase
  end

endmodule""")
    return '\n'.join(out) + '\n'


OUTPUTS = {
    os.path.join(GEN, 'rd68021_eamode_rom.sv'): eamode_rom,
    os.path.join(GEN, 'rd68021_frame_pkg.sv'): frame_pkg,
    os.path.join(GEN, 'rd68021_eadec_rom.sv'): eadec_rom,
    os.path.join(GEN, 'rd68021_ucode_pkg.sv'): ucode_pkg,
    os.path.join(GEN, 'rd68021_ucode_rom.sv'): ucode_rom,
    os.path.join(GEN, 'rd68021_decode_rom.sv'): decode_rom,
    os.path.join(ROOT, 'build', 'checkpoint-tables.md'): doc_tables,
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true',
                    help='fail if the checked-in files are stale')
    args = ap.parse_args()

    bad = frames.check() + isa.check()
    if bad:
        print('FAIL: the tables are not self-consistent')
        for b in bad:
            print('  %s' % b)
        return 1

    stale = []
    for path, fn in sorted(OUTPUTS.items()):
        text = fn()
        if args.check:
            if not os.path.exists(path):
                if path.startswith(os.path.join(ROOT, 'build')):
                    continue          # build/ is not committed
                stale.append(path)
            elif open(path).read() != text:
                stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w') as fh:
                fh.write(text)

    if args.check:
        if stale:
            print('FAIL: %d generated file(s) are stale -- run `make ucode`:'
                  % len(stale))
            for p in stale:
                print('  %s' % os.path.relpath(p, ROOT))
            return 1
        have, use, spare = frames.budget()
        print('  ucode-check: %d microwords, %d opcode patterns, %d of %d '
              'checkpoint bits used' % (len(program.WORDS),
                                        len(program.PATTERNS), use, have))
    else:
        have, use, spare = frames.budget()
        _lay, uww = isa.layout()
        print('  ucode: %d files; %d microwords of %d bits, %d opcode patterns, '
              '%d of %d checkpoint bits used, %d words spare'
              % (len(OUTPUTS), len(program.WORDS), uww, len(program.PATTERNS),
                 use, have, len(spare)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
